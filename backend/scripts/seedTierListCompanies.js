async function seedTierListCompanies(targetPool) {
  const pool = targetPool || mysql.createPool({
    host: process.env.DB_HOST || 'db',
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_USER || 'money_user',
    password: process.env.DB_PASSWORD || 'myroot',
    database: process.env.DB_NAME || 'money_tracker'
  });

  console.log(`Starting Tier-List & User-Curated companies ingestion...`);

  // 1. Fetch user profile for scoring
  const [[profile]] = await pool.query('SELECT * FROM jobhunt_profile LIMIT 1');
  if (!profile) {
    console.error('No career profile found in jobhunt_profile. Aborting.');
    if (!targetPool) await pool.end();
    return;
  }

  // 2. Ingest / Upsert all Organizations (100% safe, never drops or deletes existing data)
  let orgsUpserted = 0;
  for (const org of TIER_LIST_ORGANIZATIONS) {
    await pool.query(`
      INSERT INTO jobhunt_organizations (
        name, short_name, sector, org_type, careers_url, notification_url, website, notes,
        quality_score, poll_frequency_days, is_active, category_group, country, region,
        visa_sponsored, currency, min_ctc_threshold
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 7, 1, ?, ?, ?, ?, ?, ?)
      ON DUPLICATE KEY UPDATE
        name = VALUES(name),
        short_name = VALUES(short_name),
        sector = VALUES(sector),
        org_type = VALUES(org_type),
        careers_url = VALUES(careers_url),
        website = VALUES(website),
        notes = VALUES(notes),
        quality_score = VALUES(quality_score),
        category_group = VALUES(category_group),
        country = VALUES(country),
        region = VALUES(region),
        visa_sponsored = VALUES(visa_sponsored),
        currency = VALUES(currency),
        min_ctc_threshold = VALUES(min_ctc_threshold),
        is_active = 1
    `, [
      org.name, org.short_name, org.sector, org.org_type, org.careers_url, org.careers_url, org.website,
      org.notes, org.quality_score, org.category_group, org.country, org.region,
      org.visa_sponsored || 0, org.currency, org.min_ctc_threshold
    ]);
    orgsUpserted++;
  }
  console.log(`Ingested / Verified ${orgsUpserted} tech organizations.`);

  // 3. Fetch full organization map
  const [orgRows] = await pool.query('SELECT id, short_name, name, quality_score, sector, org_type, category_group, country, region FROM jobhunt_organizations');
  const orgMap = {};
  orgRows.forEach(r => {
    if (r.short_name) orgMap[r.short_name] = r;
    if (r.name) orgMap[r.name] = r;
  });

  // 4. Ingest and score verified opportunities
  let oppsUpserted = 0;
  for (const opp of VERIFIED_ACTIVE_OPPORTUNITIES) {
    const org = orgMap[opp.org_short];
    if (!org) {
      console.warn(`Org ${opp.org_short} not found in registry, skipping opportunity ${opp.title}`);
      continue;
    }

    // Compute score using pure function
    const scored = computeOpportunityScore(profile, opp, org);

    // Check if opportunity already exists by title + org_id
    const [[existing]] = await pool.query(
      'SELECT id FROM jobhunt_opportunities WHERE org_id = ? AND title = ? LIMIT 1',
      [org.id, opp.title]
    );

    if (existing) {
      await pool.query(`
        UPDATE jobhunt_opportunities SET
          vacancies = ?, pay_scale = ?, ctc_min = ?, ctc_max = ?, compensation_display = ?,
          required_degree = ?, required_branch = ?, min_experience_years = ?, max_age = ?, min_age = ?,
          required_skills = ?, location = ?, job_type = ?, category = ?, category_group = ?,
          country = ?, region = ?, currency = ?, visa_sponsored = ?, source_type = ?, source_url = ?,
          apply_url = ?, posted_date = ?, application_deadline = ?, notes = ?,
          raw_text = ?, requires_gate = 0, is_verified_active = 1, is_archived = 0,
          verification_source = ?, eligibility_pct = ?, profile_match_pct = ?, compensation_score = ?,
          career_potential_score = ?, competition_signal = ?, application_difficulty_score = ?,
          org_quality_score = ?, deadline_urgency_score = ?, opportunity_score = ?, recommendation = ?
        WHERE id = ?
      `, [
        opp.vacancies, opp.pay_scale, opp.ctc_min, opp.ctc_max, opp.compensation_display,
        opp.required_degree, opp.required_branch, opp.min_experience_years, opp.max_age, opp.min_age,
        opp.required_skills, opp.location, opp.job_type, opp.category, opp.category_group,
        opp.country, opp.region, opp.currency, opp.visa_sponsored, opp.source_type, opp.source_url,
        opp.apply_url, opp.posted_date, opp.application_deadline, opp.highlights || opp.notes || '',
        opp.raw_text, opp.verification_source, scored.eligibility, scored.profile_match, scored.compensation,
        scored.career_potential, scored.competition_signal, scored.application_difficulty,
        scored.org_quality, scored.deadline_urgency, scored.opportunity_score, scored.recommendation,
        existing.id
      ]);
    } else {
      await pool.query(`
        INSERT INTO jobhunt_opportunities (
          org_id, title, vacancies, pay_scale, ctc_min, ctc_max, compensation_display,
          required_degree, required_branch, min_experience_years, max_age, min_age,
          required_skills, location, job_type, category, category_group,
          country, region, currency, visa_sponsored, source_type, source_url,
          apply_url, posted_date, application_deadline, notes,
          raw_text, requires_gate, is_verified_active, is_archived,
          verification_source, eligibility_pct, profile_match_pct, compensation_score,
          career_potential_score, competition_signal, application_difficulty_score,
          org_quality_score, deadline_urgency_score, opportunity_score, recommendation
        ) VALUES (
          ?, ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?,
          ?, 0, 1, 0,
          ?, ?, ?, ?,
          ?, ?, ?,
          ?, ?, ?, ?
        )
      `, [
        org.id, opp.title, opp.vacancies, opp.pay_scale, opp.ctc_min, opp.ctc_max, opp.compensation_display,
        opp.required_degree, opp.required_branch, opp.min_experience_years, opp.max_age, opp.min_age,
        opp.required_skills, opp.location, opp.job_type, opp.category, opp.category_group,
        opp.country, opp.region, opp.currency, opp.visa_sponsored, opp.source_type, opp.source_url,
        opp.apply_url, opp.posted_date, opp.application_deadline, opp.highlights || opp.notes || '',
        opp.raw_text, opp.verification_source, scored.eligibility, scored.profile_match, scored.compensation,
        scored.career_potential, scored.competition_signal, scored.application_difficulty,
        scored.org_quality, scored.deadline_urgency, scored.opportunity_score, scored.recommendation
      ]);
    }
    oppsUpserted++;
  }

  console.log(`Upserted and rescored ${oppsUpserted} verified opportunities.`);

  // 5. Run lifecycle maintenance to ensure retention rules
  console.log(`Running lifecycle maintenance to ensure expiration & recency policies...`);
  await runOpportunitiesLifecycle(pool);

  console.log(`Sync complete! All companies & verified roles active.`);
  if (!targetPool) await pool.end();
}

if (require.main === module) {
  seedTierListCompanies()
    .then(() => process.exit(0))
    .catch(err => {
      console.error('Fatal error during seed:', err);
      process.exit(1);
    });
}

